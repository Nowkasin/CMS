def help_page(request):
    permissions = request.session.get('cms_permissions', {})
    sections = [
        {
            'key': key, 'title': title, 'summary': summary,
            'url': reverse(url_name), 'demo': demo, 'steps': steps,
        }
        for key, perm, title, summary, url_name, demo, steps in HELP_SECTIONS
        if permissions.get(perm)
    ]
    return render(request, 'meters/help.html', {
        'sections': sections,
        'has_upload': bool(permissions.get('excel_upload')),
        'legend': STATUS_LEGEND,
        'faq': FAQ,
    })
